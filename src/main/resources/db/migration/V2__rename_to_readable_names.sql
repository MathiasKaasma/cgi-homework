alter table notification alter column status varchar(16);
update notification set status = case status
    when 'N' then 'PENDING'
    when 'S' then 'SENT'
    when 'E' then 'FAILED'
    when 'U' then 'UNSUPPORTED'
    when 'R' then 'REJECTED'
end;
comment on column notification.status is 'PENDING, SENT, FAILED, UNSUPPORTED or REJECTED';

